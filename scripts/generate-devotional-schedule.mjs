/**
 * Write public/devotional-schedule.json: every published devotional, including
 * ones whose publish date has not arrived yet.
 *
 * 2026-10-06. Bart, going off grid for eleven days: "I cannot have this fail."
 *
 * The devotional email has two senders and both are unreliable in the same way.
 * The GitHub job runs four to six times a day at GitHub's discretion; it has
 * carried this for months purely because one of those runs usually lands shortly
 * after midnight Central. On October 6 the last run was 11:52pm the night before
 * and the next had not come by morning, so nothing sent.
 *
 * The 6:20am Vercel cron exists to cover exactly that, and it never has. It read
 * the site's content list, and that list deliberately excludes anything dated in
 * the future, because the website must not show a devotional before its day. So
 * a devotional only entered the list once a rebuild happened to run on its own
 * publish date, which is the same race by another name. Reading the markdown
 * files directly was the right instinct, and the right instinct did not survive
 * contact with deployment: the 302 files were not bundled into the function, so
 * the fix fell back to the stale list every morning and changed nothing.
 *
 * This file is the fix. It is generated by the same build that writes
 * knowledge.json, it carries future dates on purpose, and it sits in public/
 * next to knowledge.json, which is already proven to reach the serverless
 * functions. One small file instead of a 302-file directory, and no race,
 * because tomorrow's devotional is in today's build.
 */
import fs from 'node:fs';
import path from 'node:path';
import matter from 'gray-matter';

const DIR = path.join(process.cwd(), 'ao-knowledge-hq-kit', 'journal', 'devotionals');
const OUT = path.join(process.cwd(), 'public', 'devotional-schedule.json');

/** A YYYY-MM-DD string, whatever shape the frontmatter used. */
function calendarDateOnly(value) {
  if (!value) return '';
  if (value instanceof Date) {
    if (Number.isNaN(value.getTime())) return '';
    // Unquoted YAML dates parse as midnight UTC, so the UTC date is the one the
    // author wrote. Reading it locally would shift the day west of Greenwich.
    return value.toISOString().slice(0, 10);
  }
  const match = String(value).trim().replace(/^["']|["']$/g, '').match(/^(\d{4}-\d{2}-\d{2})/);
  return match ? match[1] : '';
}

/** The same summary the content list carries, built the same way. */
function emailSummaryFrom(frontmatter, body) {
  let summary = String(frontmatter?.summary || '').trim();
  if (!summary && body) {
    const paragraphs = String(body)
      .split(/\n\s*\n/)
      .map((p) => p.trim())
      .filter((p) => p.length > 0 && !p.startsWith('#'));
    const first = paragraphs[0] || String(body).trim();
    summary = first.length > 400 ? `${first.slice(0, 397).trim()}...` : first;
  }
  return summary
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/\*(.+?)\*/g, '$1')
    .replace(/\[(.+?)\]\(.+?\)/g, '$1')
    .replace(/#{1,6}\s+/g, '')
    .replace(/>\s+/g, '')
    .replace(/\n+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function main() {
  let files;
  try {
    files = fs.readdirSync(DIR).filter((n) => n.endsWith('.md') && n !== 'TEMPLATE.md');
  } catch (err) {
    console.error(`generate-devotional-schedule: cannot read ${DIR}: ${err.message}`);
    process.exit(1);
  }

  const entries = [];
  const problems = [];

  for (const name of files) {
    let parsed;
    try {
      parsed = matter(fs.readFileSync(path.join(DIR, name), 'utf8'));
    } catch (err) {
      problems.push(`${name}: unreadable (${err.message})`);
      continue;
    }
    const fm = parsed.data || {};
    if (String(fm.status || '').trim() !== 'published') continue;

    const publishDate = calendarDateOnly(fm.publish_date) || calendarDateOnly(fm.date);
    const title = String(fm.title || '').trim();
    const slug = String(fm.slug || name.replace(/\.md$/, '')).trim();

    if (!publishDate || !title || !slug) {
      problems.push(`${name}: missing ${!publishDate ? 'publish_date' : !title ? 'title' : 'slug'}`);
      continue;
    }

    entries.push({
      slug,
      title,
      publish_date: publishDate,
      date: publishDate,
      status: 'published',
      summary: String(fm.summary || '').trim(),
      email_summary: emailSummaryFrom(fm, parsed.content),
      scripture_reference: String(fm.scripture_reference || '').trim(),
    });
  }

  entries.sort((a, b) => a.publish_date.localeCompare(b.publish_date) || a.slug.localeCompare(b.slug));

  // A devotional on two files for the same day would send two emails.
  const byDate = new Map();
  for (const e of entries) {
    if (!byDate.has(e.publish_date)) byDate.set(e.publish_date, []);
    byDate.get(e.publish_date).push(e.slug);
  }

  const today = new Date().toISOString().slice(0, 10);
  const upcoming = entries.filter((e) => e.publish_date >= today);

  fs.writeFileSync(
    OUT,
    JSON.stringify(
      { generated_at: new Date().toISOString(), count: entries.length, devotionals: entries },
      null,
      2
    )
  );

  console.log(`📖 devotional-schedule.json: ${entries.length} published devotionals`);
  console.log(`   ${upcoming.length} dated today or later, through ${entries[entries.length - 1]?.publish_date || 'n/a'}`);
  for (const p of problems) console.warn(`   ⚠️  ${p}`);

  // The point of this file is that tomorrow is in it. If it is not, the build
  // should say so loudly rather than ship a file that recreates the old race.
  const tomorrow = new Date(Date.now() + 86400000).toISOString().slice(0, 10);
  if (!byDate.has(today) && !byDate.has(tomorrow)) {
    console.warn(`   ⚠️  Nothing scheduled for ${today} or ${tomorrow}.`);
  }
}

main();
