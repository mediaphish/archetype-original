/**
 * Pure regression checks for manual header-upload fact formatting + meta filtering.
 * Run: node lib/ao/manualHeaderUploadFact.selftest.mjs
 */
import {
  formatManualHeaderUploadFact,
  MANUAL_HEADER_UPLOAD_KIND,
} from './manualHeaderUploadFact.js';

function assert(cond, msg) {
  if (!cond) throw new Error(msg);
}

{
  const fact = formatManualHeaderUploadFact({
    slug: 'scoreboard-leadership',
    imageUrl: 'https://example.com/scoreboard.png',
    title: 'Scoreboard Leadership',
    timestamp: '2026-08-12T01:00:00.000Z',
  });
  assert(/\[SYSTEM\]/.test(fact), 'fact has SYSTEM marker');
  assert(/scoreboard-leadership/.test(fact), 'fact includes slug');
  assert(/https:\/\/example\.com\/scoreboard\.png/.test(fact), 'fact includes image URL');
  assert(/Scoreboard Leadership/.test(fact), 'fact includes title');
  assert(/not generated by Auto/.test(fact), 'fact clarifies source');
  assert(/2026-08-12T01:00:00\.000Z/.test(fact), 'fact includes timestamp');
}

{
  // Simulate the filter chat.js will apply to loaded system rows
  const rows = [
    {
      id: 'a',
      content: formatManualHeaderUploadFact({
        slug: 'one',
        imageUrl: 'https://x/1.png',
        timestamp: '2026-08-12T00:00:00.000Z',
      }),
      meta: { kind: MANUAL_HEADER_UPLOAD_KIND, consumed: false },
    },
    {
      id: 'b',
      content: 'unrelated system note',
      meta: { kind: 'other', consumed: false },
    },
    {
      id: 'c',
      content: formatManualHeaderUploadFact({
        slug: 'two',
        imageUrl: 'https://x/2.png',
        timestamp: '2026-08-12T00:01:00.000Z',
      }),
      meta: { kind: MANUAL_HEADER_UPLOAD_KIND, consumed: true },
    },
  ];

  const facts = [];
  const messageIds = [];
  for (const row of rows) {
    const meta = row.meta || {};
    if (meta.kind !== MANUAL_HEADER_UPLOAD_KIND) continue;
    if (meta.consumed === true) continue;
    facts.push(row.content);
    messageIds.push(row.id);
  }

  assert(facts.length === 1, 'only unconsumed manual-upload facts included');
  assert(messageIds[0] === 'a', 'id of unconsumed fact kept');
  assert(/scoreboard|one/.test(facts[0]) && /https:\/\/x\/1\.png/.test(facts[0]), 'context has URL + slug');
}

console.log('manualHeaderUploadFact.selftest.mjs: ok');
