/**
 * Self-check for false-denial gate (image presence).
 * Run: node lib/ao/gateDenialClaims.selftest.mjs
 */
import {
  extractImageEvidenceUrls,
  findFalseDenialClaims,
  annotateFalseDenialClaims,
} from './gateDenialClaims.js';

function assert(cond, msg) {
  if (!cond) throw new Error(msg);
}

const CONTEXT_WITH_IMAGE =
  `## APPROVED DRAFTS PENDING PUBLISH — CRITICAL CONTEXT\n` +
  `- [journal] Scoreboard Leadership | slug: scoreboard-leadership | Part 1 | Status: approved | ` +
  `image saved at: https://cdn.example.com/headers/scoreboard-leadership.jpg | Approved: 2026-08-12`;

const DENIAL_REPLY =
  `I don't see a URL or file path attached to this message. ` +
  `If you upload the header again I can attach it.`;

// Confirmed incident: denial + image saved at → must fire and include URL
{
  const urls = extractImageEvidenceUrls(CONTEXT_WITH_IMAGE);
  assert(urls.length === 1, 'expected one evidence URL from drafts context');
  assert(
    urls[0] === 'https://cdn.example.com/headers/scoreboard-leadership.jpg',
    'expected exact saved URL'
  );

  const { falseDenials } = findFalseDenialClaims(DENIAL_REPLY, {
    contextText: CONTEXT_WITH_IMAGE,
  });
  assert(falseDenials.length === 1, 'expected image_denial to fire');
  assert(falseDenials[0].ruleId === 'image_denial', 'expected image_denial rule');

  const annotated = annotateFalseDenialClaims(DENIAL_REPLY, {
    contextText: CONTEXT_WITH_IMAGE,
  });
  assert(annotated.appendedNote, 'expected visible correction note');
  assert(
    annotated.appendedNote.includes('https://cdn.example.com/headers/scoreboard-leadership.jpg'),
    'correction note must include the real URL'
  );
  assert(
    annotated.reply.startsWith(DENIAL_REPLY.trim().slice(0, 20)),
    'original reply must be preserved at the top'
  );
}

// Conservatism: same denial phrase, no image evidence → must NOT fire
{
  const contextNoImage =
    `- [journal] Scoreboard Leadership | slug: scoreboard-leadership | ` +
    `image saved at: no image saved yet | Approved: 2026-08-12`;
  const { falseDenials } = findFalseDenialClaims(DENIAL_REPLY, {
    contextText: contextNoImage,
  });
  assert(falseDenials.length === 0, 'no concrete URL → must not fire');

  const empty = findFalseDenialClaims(DENIAL_REPLY, { contextText: '' });
  assert(empty.falseDenials.length === 0, 'empty context → must not fire');
}

// Manual header upload fact also counts as evidence
{
  const manualFact =
    `[SYSTEM] User manually uploaded a header image directly to draft 'scoreboard-leadership' ` +
    `at 2026-08-12T02:08:41.000Z. Image URL: https://cdn.example.com/manual-upload.png. ` +
    `This was not generated by Auto.`;
  const { falseDenials } = findFalseDenialClaims(
    "I can't see any image attached to this draft.",
    { contextText: manualFact }
  );
  assert(falseDenials.length === 1, 'manual upload fact should back a false-denial catch');
}

// Denial without image/URL subject nearby should not fire (conservatism)
{
  const { falseDenials } = findFalseDenialClaims(
    "I don't see a scheduling conflict for tomorrow.",
    { contextText: CONTEXT_WITH_IMAGE }
  );
  assert(falseDenials.length === 0, 'unrelated denial should not fire');
}

console.log('gateDenialClaims.selftest: PASS');
