/**
 * Builds the SQL seed text for ali_v3_items from lib/ali-v3-bank.js.
 * Used by scripts/ali/build-v3-seed.mjs and by the tests (seed must match the bank).
 */
import { listV3Items, validateV3Bank, V3_INSTRUMENT_VERSION } from './ali-v3-bank.js';

const q = (s) => (s === null || s === undefined ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`);
const b = (v) => (v ? 'TRUE' : 'FALSE');

export function buildSeedSql() {
  const problems = validateV3Bank();
  if (problems.length) throw new Error(`Bank has problems:\n- ${problems.join('\n- ')}`);
  const items = listV3Items();
  const rows = items.map(
    (it) =>
      `  (${q(it.stable_id)}, ${q(V3_INSTRUMENT_VERSION)}, ${q(it.idea_id)}, ${q(it.idea_label)}, ${q(it.condition)}, ${q(it.kind)}, ${q(it.version)}, ${q(it.team_text)}, ${q(it.leader_text)}, ${b(it.is_reversed)}, ${b(it.is_trial)}, 'active', ${q(it.note)})`
  );
  const core = items.filter((i) => !i.is_trial).length;
  const trial = items.length - core;
  return `-- ALI v3 question bank seed. GENERATED by scripts/ali/build-v3-seed.mjs from lib/ali-v3-bank.js.
-- Do not edit by hand: change lib/ali-v3-bank.js and run the script again.
-- Apply after database/ALI_V3_INSTRUMENT.sql. Safe to run more than once (upsert).
-- ${items.length} items: ${core} core (17 ideas x 4 versions), ${trial} trial (unscored).

BEGIN;

INSERT INTO ali_v3_items
  (stable_id, instrument_version, idea_id, idea_label, condition, kind, version, team_text, leader_text, is_reversed, is_trial, status, note)
VALUES
${rows.join(',\n')}
ON CONFLICT (stable_id) DO UPDATE SET
  idea_label  = EXCLUDED.idea_label,
  condition   = EXCLUDED.condition,
  kind        = EXCLUDED.kind,
  team_text   = EXCLUDED.team_text,
  leader_text = EXCLUDED.leader_text,
  is_reversed = EXCLUDED.is_reversed,
  is_trial    = EXCLUDED.is_trial,
  status      = EXCLUDED.status,
  note        = EXCLUDED.note,
  updated_at  = NOW();

COMMIT;

-- Check: SELECT is_trial, COUNT(*) FROM ali_v3_items GROUP BY is_trial;  -- false ${core}, true ${trial}
`;
}
